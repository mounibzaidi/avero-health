"""Write supabase/seed.sql from content/fiches/*.json: one subjects row and one version per fiche.

    python3 tools/import/make_seed.py

A fiche whose meta.status is "published" is seeded as published (stroke and ACS were live in the old
app); the others as unpublished drafts. Re-running the seed inserts nothing twice.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FICHES = ROOT / "content" / "fiches"
OUT = ROOT / "supabase" / "seed.sql"


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main():
    lines = ["-- Generated by tools/import/make_seed.py from content/fiches. Do not edit.", "begin;", ""]
    for path in sorted(FICHES.glob("*.json")):
        f = json.loads(path.read_text(encoding="utf-8"))
        sid, m = path.stem, f["meta"]
        body = json.dumps(f, ensure_ascii=False)
        assert "$fiche$" not in body
        published = "now()" if m["status"] == "published" else "null"
        lines += [
            f"insert into subjects (id, title, template, specialite) values ({lit(sid)}, {lit(m['title'])}, {lit(m['template'])}, {lit(m['specialite'])})",
            "  on conflict (id) do nothing;",
            f"insert into fiche_versions (subject_id, version, content, published_at) values ({lit(sid)}, 1, $fiche${body}$fiche$::jsonb, {published})",
            "  on conflict (subject_id, version) do nothing;",
            "",
        ]
    lines.append("commit;")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
