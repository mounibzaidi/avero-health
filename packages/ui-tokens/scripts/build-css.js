/**
 * Writes theme.css for the dashboard (Tailwind 4) from tokens.js.
 * `node scripts/build-css.js --check` fails when theme.css is out of date.
 */
const fs = require("fs");
const path = require("path");
const { COLOR_NAMES, cssVars, font, radius, shadow } = require("../tokens");

const block = (vars) => Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join("\n");

const fontFaces = Object.entries(font.files)
  .map(
    ([weight, file]) => `@font-face {
  font-family: "${font.sans}";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("./fonts/${file}") format("truetype");
}`,
  )
  .join("\n");

const theme = [
  ...Object.entries(COLOR_NAMES).map(([name, suffix]) => `  --color-${name}: rgb(var(--c-${suffix}));`),
  `  --font-sans: "${font.sans}", system-ui, sans-serif;`,
  `  --font-mono: ${font.mono.web};`,
  ...Object.entries(radius).map(([name, px]) => `  --radius${name === "DEFAULT" ? "" : "-" + name}: ${px}px;`),
  `  --shadow-surface: ${shadow.surface};`,
  `  --shadow-control: ${shadow.control};`,
  `  --shadow-sheet: ${shadow.sheet};`,
].join("\n");

const css = `/* Generated by scripts/build-css.js from tokens.js. Do not edit. */

${fontFaces}

:root {
${block(cssVars("light"))}
}

/* Dark: set data-theme="dark" on <html> (or on any wrapper). */
[data-theme="dark"] {
${block(cssVars("dark"))}
}

@theme inline {
${theme}
}
`;

const out = path.join(__dirname, "..", "theme.css");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== css) {
    console.error("theme.css is out of date: run npm run build --workspace @medguides/ui-tokens");
    process.exit(1);
  }
  console.log("theme.css is up to date");
} else {
  fs.writeFileSync(out, css);
  console.log("wrote theme.css");
}
